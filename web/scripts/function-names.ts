// Regenerates src/runtime/function-names.ts from the keys of the F table in functions.ts.
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../src/runtime/functions.ts", import.meta.url), "utf8");
const body = src.slice(src.indexOf("const F: Record"));
const names = [...new Set([...body.matchAll(/^    ([a-z_0-9]+): /gm)].map((m) => m[1]))].sort();
writeFileSync(new URL("../src/runtime/function-names.ts", import.meta.url),
  `// Generated by scripts/function-names.ts.\nexport const FUNCTIONS: string[] = ${JSON.stringify(names)};\n`);
console.log(`${names.length} functions`);
